// barIcons maps the pixel glyphs used on the key bar to their anti-aliased SVG renders
// (icons/*.svg, rasterized to assets/icons/*.png at 20x20).
var barIcons = map[*string]string{
	&artOpen[0]: "open", &artStar[0]: "star", &artInfo[0]: "info", &artGear[0]: "gear",
	&artLock[0]: "lock", &artBack[0]: "back", &artOK[0]: "ok", &artNo[0]: "no",
	&artLeft[0]: "left", &artRight[0]: "right", &artMinus[0]: "minus", &artPlus[0]: "plus",
	&artRefresh[0]: "refresh", &artEye[0]: "eye", &artBell[0]: "bell", &artPower[0]: "power",
}

func barIcon(art []string) *Tex {
	if len(art) == 0 {
		return nil
	}
	if n, ok := barIcons[&art[0]]; ok {
		return tex("icons/" + n + ".png")
	}
	return nil
}

// tileIcons maps the settings glyphs to their SVG renders (icons/settings/*.svg, 24x24).
var tileIcons = map[*string]string{
	&artScreen[0]: "screen", &artSpeaker[0]: "speaker", &artWifi[0]: "wifi", &artEthernet[0]: "ethernet",
	&artBluetooth[0]: "bluetooth", &artPlug[0]: "ports", &artBattery[0]: "battery", &artLauncher[0]: "launcher",
	&artDev[0]: "developer", &artUser[0]: "user", &artClock[0]: "clock", &artSystem[0]: "system",
}

func tileIcon(art []string) *Tex {
	if len(art) == 0 {
		return nil
	}
	if n, ok := tileIcons[&art[0]]; ok {
		return tex("tiles/" + n + ".png")
	}
	return nil
}
