"""Convert the ds.css assets for the 320x170 screen.

usage: py tools/mkassets.py <ds.css-main/src/assets>
Writes assets/*.png (textures halved to native pixels, nearest neighbour) and fontdata.go
(the two fonts pre-rendered at pixel-exact sizes)."""
import os, sys
from PIL import Image, ImageFont, ImageDraw

src = sys.argv[1]
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(here, "assets")
os.makedirs(out, exist_ok=True)

for name in sorted(os.listdir(os.path.join(src, "images"))):
    if not name.endswith(".png"):
        continue
    im = Image.open(os.path.join(src, "images", name)).convert("RGBA")
    im = im.resize((max(im.width // 2, 1), max(im.height // 2, 1)), Image.NEAREST)
    im.save(os.path.join(out, name))

def glyphs(path, size, chars):
    f = ImageFont.truetype(path, size)
    ascent, descent = f.getmetrics()
    res = []
    for ch in chars:
        adv = int(round(f.getlength(ch)))
        box = f.getbbox(ch)
        im = Image.new("1", (adv + size * 2, ascent + descent + size), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((size // 2, 0), ch, font=f, fill=1)
        bb = im.getbbox()
        if bb is None:
            res.append((ch, adv, 0, 0, 0, 0, []))
            continue
        x0, y0, x1, y1 = bb
        rows = []
        for y in range(y0, y1):
            bits = 0
            for x in range(x0, x1):
                if im.getpixel((x, y)):
                    bits |= 1 << (x - x0)
            rows.append(bits)
        res.append((ch, adv, x0 - size // 2, y0, x1 - x0, y1 - y0, rows))
    return ascent, descent, res

def emit(var, path, size, chars):
    ascent, descent, gs = glyphs(path, size, chars)
    lines = [f"var {var} = &bmFont{{Ascent: {ascent}, Descent: {descent}, G: map[rune]bmGlyph{{"]
    for ch, adv, ox, oy, w, h, rows in gs:
        r = ", ".join(f"0x{v:x}" for v in rows)
        lines.append(f"\t{ord(ch)}: {{Adv: {adv}, OX: {ox}, OY: {oy}, W: {w}, H: {h}, Rows: []uint64{{{r}}}}},")
    lines.append("}}")
    return "\n".join(lines)

text = os.path.join(src, "fonts", "nitrods-font.ttf")
clock = os.path.join(src, "fonts", "ds-clock-numbers-font.ttf")
ascii_ = "".join(chr(c) for c in range(32, 127)) + "°•…"
digits = "0123456789: -/"
go = ["// Code generated by tools/mkassets.py from the ds.css fonts. DO NOT EDIT.", "", "package main", ""]
go.append(emit("fontText", text, 10, ascii_))
go.append("")
go.append(emit("fontClock10", clock, 10, digits))
go.append("")
go.append(emit("fontClock15", clock, 15, digits))
go.append("")
go.append(emit("fontClock20", clock, 20, digits))
go.append("")
go.append(emit("fontClock30", clock, 30, digits))
open(os.path.join(here, "fontdata.go"), "w", newline="\n").write("\n".join(go) + "\n")
print("assets:", len(os.listdir(out)), "fontdata.go written")
